def compute_price(item):
    name = (item.get("name") or "").strip()
    if name in UNPRICED_ITEMS:
        return None
    if name in EXACT_PRICES:
        return round(EXACT_PRICES[name], 2)
    sub = item.get("subcategory") or ""
    if sub in SUBCATEGORY_DEFAULTS:
        return round(SUBCATEGORY_DEFAULTS[sub], 2)
    return round(CATEGORY_DEFAULTS.get(item.get("category") or "Sonstiges", 2.49), 2)


def main():
    items = json.loads(FE_TAX.read_text(encoding="utf-8"))
    for it in items:
        it["reference_price_eur"] = compute_price(it)

    serialized = json.dumps(items, ensure_ascii=False, indent=2) + "\n"
    FE_TAX.write_text(serialized, encoding="utf-8")
    BE_TAX.write_text(serialized, encoding="utf-8")

    priced = sum(1 for it in items if it.get("reference_price_eur") is not None)
    print(f"Enriched {len(items)} items ({priced} with curated EUR reference_price_eur).")


if __name__ == "__main__":
    main()
